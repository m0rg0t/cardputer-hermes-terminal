#!/usr/bin/env python3
"""Generate include/hermes_terminal/latin_font.h from glyph art.

The stock 6x8 terminal font has ASCII glyphs only. This 5x7 set covers
Spanish and extended Latin characters:
Á, É, Í, Ó, Ú, Ü, Ñ, Ç
á, é, í, ó, ú, ü, ñ, ç
¡, ¿
"""
from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "include" / "hermes_terminal" / "latin_font.h"

# 5 columns, 7 rows. '#' = pixel on, '.' = pixel off.
GLYPHS = """
Á ...#. .###. #...# ##### #...# #...# #...#
É ...#. ##### #.... ####. #.... #.... #####
Í ...#. .###. ..#.. ..#.. ..#.. ..#.. .###.
Ó ...#. .###. #...# #...# #...# #...# .###.
Ú ...#. #...# #...# #...# #...# #...# .###.
Ü .#.#. #...# #...# #...# #...# #...# .###.
Ñ .#.## #...# ##..# #.#.# #..## #...# #...#
Ç .###. #...# #.... #.... #...# .###. ..#..
á ...#. ..#.. .###. ....# .#### #...# .####
é ...#. ..#.. .###. #...# ##### #.... .###.
í ...#. ..#.. ..... .##.. ..#.. ..#.. .###.
ó ...#. ..#.. .###. #...# #...# #...# .###.
ú ...#. ..#.. #...# #...# #...# #...# .####
ü .#.#. ..... #...# #...# #...# #...# .####
ñ .#.## ..... ####. #...# #...# #...# #...#
ç ..... ..... .###. #.... #.... .###. ..#..
¡ ..#.. ..... ..#.. ..#.. ..#.. ..#.. ..#..
¿ ..#.. ..... ..#.. .#... #.... #...# .###.
"""

EXPECTED = [
    "Á", "É", "Í", "Ó", "Ú", "Ü", "Ñ", "Ç",
    "á", "é", "í", "ó", "ú", "ü", "ñ", "ç",
    "¡", "¿"
]

CODEPOINTS = [
    (0x00C1, "Á"), (0x00C9, "É"), (0x00CD, "Í"), (0x00D3, "Ó"),
    (0x00DA, "Ú"), (0x00DC, "Ü"), (0x00D1, "Ñ"), (0x00C7, "Ç"),
    (0x00E1, "á"), (0x00E9, "é"), (0x00ED, "í"), (0x00F3, "ó"),
    (0x00FA, "ú"), (0x00FC, "ü"), (0x00F1, "ñ"), (0x00E7, "ç"),
    (0x00A1, "¡"), (0x00BF, "¿"),
]


def main() -> int:
    rows = [line.split() for line in GLYPHS.strip().splitlines()]
    letters = [row[0] for row in rows]
    if letters != EXPECTED:
        raise SystemExit(f"glyph order mismatch: {letters}")
    lines = []
    for row in rows:
        letter, *art = row
        if len(art) != 7 or any(len(r) != 5 for r in art):
            raise SystemExit(f"bad art for {letter}")
        packed = ", ".join(
            "0x%02X" % int("".join("1" if c == "#" else "0" for c in r), 2)
            for r in art)
        lines.append(f"    {{{packed}}},  // {letter} U+{ord(letter):04X}")

    lookup_cases = []
    for idx, (cp, name) in enumerate(CODEPOINTS):
        lookup_cases.append(f"        case 0x{cp:04X}: return {idx};  // {name}")

    content = (
        "#pragma once\n\n"
        "#include <cstdint>\n\n"
        "// 5x7 Latin / Spanish glyphs for the 6x8 terminal font cell. Rows top to\n"
        "// bottom, bit 4 is the leftmost column.\n"
        "// Generated by scripts/generate_latin_font.py; do not edit.\n"
        "namespace hermes_terminal {\n\n"
        f"constexpr int kLatinGlyphCount = {len(rows)};\n"
        "const std::uint8_t kLatinGlyphs[kLatinGlyphCount][7] = {\n"
        + "\n".join(lines) + "\n"
        "};\n\n"
        "// Returns the glyph row index for a code point, or -1 if not covered.\n"
        "inline int latinGlyphIndex(std::uint32_t codePoint)\n"
        "{\n"
        "    switch (codePoint) {\n"
        + "\n".join(lookup_cases) + "\n"
        "        default: return -1;\n"
        "    }\n"
        "}\n\n"
        "}  // namespace hermes_terminal\n"
    )
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} with {len(rows)} glyphs")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
